import { Route, Routes } from 'react-router';
import { PuzzlePage } from './PuzzlePage';
import { PuzzlesHomePage } from './PuzzlesHomePage';
import { TrainPage } from './TrainPage';
import { LichessDailyPage } from './lichess/LichessDailyPage';
import { LichessHomePage } from './lichess/LichessHomePage';
import { LichessTrainPage } from './lichess/LichessTrainPage';

export { usePuzzleSummary, type PuzzleSummary } from './model/usePuzzleData';
export { useLichessSummary, type LichessSummary } from './lichess/model/useLichessData';

/**
 * Puzzles feature root, mounted by the app at `/puzzles/*` (with the tab bar).
 * - `#/puzzles`          home: train, counts, filters, recent mistakes
 * - `#/puzzles/train`    a session of due then new puzzles (filters via query string)
 * - `#/puzzles/p/:id`    one puzzle
 * - `#/puzzles/lichess`        Lichess puzzles home: rating, daily puzzle, stats (separate from the above)
 * - `#/puzzles/lichess/play`   rated puzzles from the bundled pack, matched to the Lichess-puzzle rating
 * - `#/puzzles/lichess/daily`  the Lichess daily puzzle
 * Puzzles are generated by the analysis service (src/services/puzzles/).
 */
export function PuzzlesFeature() {
  return (
    <Routes>
      <Route index element={<PuzzlesHomePage />} />
      <Route path="train" element={<TrainPage />} />
      <Route path="p/:id" element={<PuzzlePage />} />
      <Route path="lichess" element={<LichessHomePage />} />
      <Route path="lichess/play" element={<LichessTrainPage />} />
      <Route path="lichess/daily" element={<LichessDailyPage />} />
    </Routes>
  );
}
